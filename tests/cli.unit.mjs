test("re-add refuses an edited file, and --overwrite replaces it", (dir) => {
  project(dir)
  van(dir, "add", "badge")
  const target = join(dir, "ui/badge/badge.css")
  appendFileSync(target, "/* my edit */\n")

  const refused = van(dir, "add", "badge")
  assert.equal(refused.code, 1, refused.all)
  assert.match(refused.all, /skipped badge \(badge\.css\)/)
  assert.match(readFileSync(target, "utf8"), /my edit/, "edit was destroyed without --overwrite")

  const forced = van(dir, "add", "badge", "--overwrite")
  assert.equal(forced.code, 0, forced.all)
  assert.doesNotMatch(readFileSync(target, "utf8"), /my edit/, "--overwrite did not replace the file")

  // --force is kept as an alias of --overwrite.
  assert.equal(van(dir, "add", "badge", "--force").code, 0)
})

test("re-add overwrites a file the consumer never touched", (dir) => {
  project(dir)
  van(dir, "add", "badge")
  const target = join(dir, "ui/badge/badge.css")

  // Simulate upstream having moved on: the local file still matches what was
  // recorded at install time, but no longer matches the kit.
  appendFileSync(target, "/* pretend this came from the kit */\n")
  const sidecarPath = join(dir, "ui/badge/.van.json")
  const sidecar = JSON.parse(readFileSync(sidecarPath, "utf8"))
  sidecar.files["badge.css"] = hashFile(target)
  writeFileSync(sidecarPath, JSON.stringify(sidecar, null, 2) + "\n")

  const r = van(dir, "add", "badge")
  assert.equal(r.code, 0, r.all)
  assert.match(r.out, /badge\.css updated/)
  assert.equal(
    readFileSync(target, "utf8"),
    readFileSync(join(repoRoot, "ui/badge/badge.css"), "utf8"),
    "unmodified file was not brought up to date",
  )
})

