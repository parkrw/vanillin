/**
 * bin/van.mjs against real scratch projects.
 * Named .unit.mjs so the browser test runner runs it as a child process.
 *
 * The CLI is exercised the way a consumer runs it — spawned, with --cwd — so
 * argv parsing, exit codes and stdout are all under test, not just the
 * exported helpers.
 */

import assert from "node:assert/strict"
import { spawnSync } from "node:child_process"
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, rmSync, appendFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { fileURLToPath } from "node:url"
import { hashFile } from "../scripts/manifest.mjs"

const repoRoot = fileURLToPath(new URL("..", import.meta.url))
const VAN = join(repoRoot, "bin", "van.mjs")
const scratch = mkdtempSync(join(tmpdir(), "van-cli-"))

let passed = 0
let failed = 0

function test(name, fn) {
  const dir = join(scratch, name.replace(/[^\w]+/g, "-"))
  mkdirSync(dir, { recursive: true })
  try {
    fn(dir)
    passed++
  } catch (err) {
    failed++
    console.error(`FAIL ${name}\n  ${err.message}`)
  }
}

/** Run van in `dir`. Colour is off so assertions can match plain strings. */
function van(dir, ...args) {
  const r = spawnSync(process.execPath, [VAN, ...args, "--cwd", dir], {
    encoding: "utf8",
    env: { ...process.env, NO_COLOR: "1" },
  })
  return { code: r.status, out: r.stdout, err: r.stderr, all: r.stdout + r.stderr }
}

/** A project with a config written straight to disk, skipping init. */
function project(dir, config = {}) {
  writeFileSync(join(dir, "van.config.json"), JSON.stringify(config, null, 2) + "\n")
  for (const name of ["globals.css", "defaults.css", "forced-colors.css"]) {
    mkdirSync(join(dir, "styles"), { recursive: true })
    writeFileSync(join(dir, "styles", name), readFileSync(join(repoRoot, "styles", name)))
  }
  return dir
}

// ── init ────────────────────────────────────────────────────────────

test("init scaffolds a buildable tree", (dir) => {
  const r = van(dir, "init")
  assert.equal(r.code, 0, r.all)

  const config = JSON.parse(readFileSync(join(dir, "van.config.json"), "utf8"))
  assert.equal(config.paths.ui, "components/ui")
  assert.ok(config.theme.brand, "no starter brand colour")

  for (const name of ["globals.css", "defaults.css", "forced-colors.css", "van.css"]) {
    assert.ok(existsSync(join(dir, "styles", name)), `styles/${name} not written`)
  }

  // The first build must already reflect the scaffolded config.
  const css = readFileSync(join(dir, "styles", "van.css"), "utf8")
  assert.match(css, /^\/\* Generated by van/)
  assert.match(css, /--primary: light-dark\(/)

  // And a rebuild is a no-op, not an error.
  assert.equal(van(dir, "build").code, 0)
})

test("init refuses to clobber an existing config", (dir) => {
  van(dir, "init")
  writeFileSync(join(dir, "van.config.json"), '{ "theme": { "radius": "1rem" } }\n')
  const r = van(dir, "init")
  assert.equal(r.code, 1)
  assert.match(r.all, /already exists/)
  assert.match(readFileSync(join(dir, "van.config.json"), "utf8"), /1rem/, "config was overwritten")
})

test("init honours components.json aliases through tsconfig paths", (dir) => {
  writeFileSync(join(dir, "tsconfig.json"), '{"compilerOptions":{"paths":{"@/*":["./src/*"]}}}\n')
  writeFileSync(
    join(dir, "components.json"),
    '{"aliases":{"ui":"@/components/ui","utils":"@/lib/utils"},"tailwind":{"css":"src/app/globals.css"}}\n',
  )
  assert.equal(van(dir, "init").code, 0)

  const config = JSON.parse(readFileSync(join(dir, "van.config.json"), "utf8"))
  assert.equal(config.paths.ui, "src/components/ui")
  assert.equal(config.paths.lib, "src/lib")
  assert.equal(config.paths.styles, "src/app")
  assert.ok(existsSync(join(dir, "src/app/globals.css")), "stylesheets ignored the detected layout")
})

